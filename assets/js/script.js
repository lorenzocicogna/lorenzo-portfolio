const menuButton = document.querySelector(".menu-toggle");
const menu = document.querySelector(".nav-menu");

function closeMenu() {
  if (!menuButton || !menu) return;
  menu.classList.remove("open");
  menuButton.setAttribute("aria-expanded", "false");
  menuButton.setAttribute("aria-label", "Open menu");
}

if (menuButton && menu) {
  menuButton.addEventListener("click", () => {
    const isOpen = menu.classList.toggle("open");
    menuButton.setAttribute("aria-expanded", String(isOpen));
    menuButton.setAttribute("aria-label", isOpen ? "Close menu" : "Open menu");
  });

  menu.querySelectorAll("a").forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  document.addEventListener("click", (event) => {
    if (!menu.contains(event.target) && !menuButton.contains(event.target)) {
      closeMenu();
    }
  });
}

const flags = document.querySelectorAll(".flag");
const translatableElements = document.querySelectorAll("[data-i18n]");

function applyLanguage(language) {
  const selected = translations[language] ? language : "en";

  translatableElements.forEach((element) => {
    const key = element.dataset.i18n;
    const value = translations[selected][key];
    if (value) element.textContent = value;
  });

  flags.forEach((flag) => {
    flag.classList.toggle("active", flag.dataset.lang === selected);
  });

  document.documentElement.lang = selected;
  localStorage.setItem("selectedLanguage", selected);
}

flags.forEach((flag) => {
  flag.addEventListener("click", () => applyLanguage(flag.dataset.lang));
});

applyLanguage(localStorage.getItem("selectedLanguage") || "en");

